@login_required
def Process_DownloadView(request, filename):
    """Serve a file generated by a Process_View from the user's upload dir."""
    filename = os.path.basename(filename)  # prevent path traversal
    dirname = file_location(request.user)
    filepath = os.path.join(dirname, filename)
    if not os.path.isfile(filepath):
        raise Http404(f"File '{filename}' not found")
    response = FileResponse(open(filepath, 'rb'),
                            content_type='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
    response['Content-Disposition'] = f'attachment; filename="{filename}"'
    return response


# --------------------------------------------------------------------------------------------------
@login_required
def Process_ProgressView(request):
    """Return the cached progress snapshot for a running process (Option B)."""
    key = request.GET.get('key')
    data = cache.get(key) if key else None
    if data is None:
        data = {'done': 0, 'total': 0, 'percent': 0, 'item': '', 'message': ''}
    return JsonResponse(data)

